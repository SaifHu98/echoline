    public static function init(string $locale): void
    {
        $locale = in_array($locale, ['ar', 'en'], true) ? $locale : 'ar';
        self::$locale = $locale;
        // Start with hardcoded messages
        self::$catalog = self::$messages[$locale] ?? [];
        // Overlay with JSON files (so dynamic translations win)
        $jsonPath = __DIR__ . '/../data/i18n/' . $locale . '.json';
        if (file_exists($jsonPath)) {
            $json = @json_decode(file_get_contents($jsonPath), true);
            if (is_array($json)) {
                self::$catalog = array_merge(self::$catalog, $json);
            }
        }
        // Fallback = English
        self::$fallback = self::$messages['en'] ?? [];
        $enPath = __DIR__ . '/../data/i18n/en.json';
        if (file_exists($enPath)) {
            $en = @json_decode(file_get_contents($enPath), true);
            if (is_array($en)) {
                self::$fallback = array_merge(self::$fallback, $en);
            }
        }
    }

    public static function t(string $key, array $params = []): string
    {
        $val = self::$catalog[$key] ?? null;
        if ($val === null) {
            $val = self::$fallback[$key] ?? $key;
        }
        foreach ($params as $k => $v) {
            $val = str_replace('{' . $k . '}', (string) $v, $val);
        }
        return $val;
    }

    public static function isRtl(): bool
    {
        return self::$locale === 'ar';
    }

    public static function locale(): string
    {
        return self::$locale;
    }

    public static function direction(): string
    {
        return self::isRtl() ? 'rtl' : 'ltr';
    }

    /** Force-clear catalog (for testing) */
    public static function resetCatalog(string $locale): void
    {
        self::init($locale);
    }
